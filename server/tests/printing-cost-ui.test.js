import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { Window } from 'happy-dom';
import * as db from '../db.js';
import { app } from '../server.js';
import { createSession } from '../auth.js';
import { getBusinessDateKey } from '../date-utils.js';

test('interface inicia sem preços, salva valor explícito e apresenta o resultado sem modificar inventário', async t => {
  db.closeDatabase(); db.initDatabase({inMemory:true,skipSeeds:true});
  db.saveUnit({id:'u',name:'Unidade Exemplo',region:'SP'});
  db.savePrinter({id:'p',name:'<img src=x onerror=alert(1)>',ip:'192.0.2.10',unitId:'u',unitName:'Unidade Exemplo',location:'Laboratório'});
  db.updateCachedStatus('p',{online:true,info:{model:'Lexmark MX622',pageCount:2000}});
  const today=getBusinessDateKey();
  db.recordPageCount('p',1000,[],{observedAt:`${today}T10:00:00Z`});
  db.recordPageCount('p',2000,[],{observedAt:`${today}T20:00:00Z`});
  const before=JSON.stringify(db.getPrinters());
  const server=app.listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
  const base=`http://127.0.0.1:${server.address().port}`;
  const window=new Window({url:base,settings:{enableJavaScriptEvaluation:true,disableJavaScriptFileLoading:true,disableCSSFileLoading:true,suppressInsecureJavaScriptEnvironmentWarning:true}});
  const source=p=>readFileSync(new URL(`../../public/${p}`,import.meta.url),'utf8');
  window.document.write(source('index.html'));window.setInterval=()=>0;window.requestAnimationFrame=()=>0;
  window.HTMLDialogElement.prototype.showModal=function(){this.open=true;};
  window.HTMLDialogElement.prototype.close=function(){this.open=false;};
  window.HTMLCanvasElement.prototype.getContext=()=>null;
  window.fetch=(url,options)=>fetch(new URL(url,base),options);
  t.after(async()=>{await window.happyDOM.abort();window.close();server.closeAllConnections();await new Promise(r=>server.close(r));db.closeDatabase();});
  window.eval(source('js/supply-semantics.js'));
  window.eval(source('js/app.js')+'\nwindow.AppState=AppState;');
  window.eval(source('js/printing-costs.js'));
  window.eval("AppState.userRole='operator';updateHeaderRoleAndUnit();");
  await window.PrintingCosts.open();assert.equal(window.document.querySelector('.printing-cost-dialog'),null);
  const admin=createSession({username:'UI-admin',role:'admin'});
  window.eval(`AppState.userRole='admin';setAuthToken('${admin.token}');updateHeaderRoleAndUnit();`);
  await window.PrintingCosts.open();
  const field=name=>window.document.getElementById(`cost-${name}`);
  field('start').value=today;field('end').value=today;
  await field('filter-form').onsubmit(new window.Event('submit',{cancelable:true}));
  assert.match(field('results').textContent,/1.000 páginas sem preço conhecido/);
  assert.equal(field('price-value').value,'','ausência não é preenchida como zero');
  assert.equal(field('price-changes').querySelectorAll('tbody tr').length,0);
  field('edit-prices').click();assert.equal(field('price-editor').hidden,false);
  field('price-value').value='0,0123';
  await field('price-form').onsubmit(new window.Event('submit',{cancelable:true}));
  assert.match(field('price-status').textContent,/Preço salvo/);
  assert.match(field('results').querySelector('.cost-total').textContent,/12,30/);
  assert.match(field('price-changes').textContent,/UI-admin/);
  field('group').value='printer';await field('filter-form').onsubmit(new window.Event('submit',{cancelable:true}));
  assert.equal(window.document.querySelector('.printing-cost-dialog img'),null,'nome do equipamento é escapado');
  field('history-start').value=today.slice(0,7);field('history-end').value=today.slice(0,7);
  await field('history-form').onsubmit(new window.Event('submit',{cancelable:true}));
  assert.match(field('history-results').textContent,/12,30/);
  field('price-value').value='-1';await field('price-form').onsubmit(new window.Event('submit',{cancelable:true}));
  assert.match(field('price-status').textContent,/não negativo/);
  assert.equal(JSON.stringify(db.getPrinters()),before);
  window.document.getElementById('btn-logout').click();assert.equal(window.document.querySelector('.printing-cost-dialog'),null);
});
